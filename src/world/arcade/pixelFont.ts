/** Lit pixels of each glyph as [x, y] pairs (precomputed: drawing is a run of fillRects). */
const LIT: Record<string, [number, number][]> = Object.fromEntries(
  Object.entries(GLYPHS).map(([ch, r]) => [ch, r.flatMap((row, y) => [...row].flatMap((c, x) => (c === '#' ? [[x, y] as [number, number]] : [])))]),
)

/** Width of `text` in screen pixels at `scale`. */
export const textWidth = (text: string, scale = 1) => (text.length ? (text.length * (GLYPH.w + GLYPH.gap) - GLYPH.gap) * scale : 0)

/**
 * Draw `text` with its top at `y`; `x` is the left edge, the centre or the right edge (`align`).
 * Unknown characters (none can come from the content) are skipped as spaces.
 */
export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  { scale = 1, color = '#fff', align = 'left' }: { scale?: number; color?: string; align?: 'left' | 'center' | 'right' } = {},
) {
  const w = textWidth(text, scale)
  let left = align === 'center' ? x - w / 2 : align === 'right' ? x - w : x
  left = Math.round(left)
  const top = Math.round(y)
  ctx.fillStyle = color
  for (let i = 0; i < text.length; i++) {
    const lit = LIT[text[i]!]
    if (lit) for (const [px, py] of lit) ctx.fillRect(left + px * scale, top + py * scale, scale, scale)
    left += (GLYPH.w + GLYPH.gap) * scale
  }
}

/** Every character the content may use has a glyph (tested). */
export const missingGlyphs = () => [...PIXEL_CHARSET].filter((ch) => !GLYPHS[ch])
